//! Fixed-cardinality execution, admission, import and consensus observations.
use crate::metrics::{NodeMetrics, StageMetrics, counter, family};
use neutrino_consensus_engine::BftAction;
use neutrino_consensus_types::Body;
use neutrino_primitives::Hash;
use neutrino_proof_system::{BlockExecutionContext, ErasedBlockExecutor, ExecutionOutcome};
use neutrino_runtime_abi::{QueryRequest, QueryResponse, TxValidity};
use neutrino_trie::{Poseidon2Hasher, Trie};
use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::sync::{
    Arc, Mutex,
    atomic::{AtomicU64, Ordering},
};
use std::time::Instant;

/// Runtime `TxValidity` codes by wire value, then a trap slot.
const VALIDITY_CODES: [&str; 9] = [
    "valid",
    "malformed",
    "bad_signature",
    "nonce_mismatch",
    "insufficient_balance",
    "unauthorized",
    "unknown_type",
    "state_read_failed",
    "runtime_trap",
];
const RUNTIME_TRAP: usize = VALIDITY_CODES.len() - 1;
const ADMISSIONS: [&str; 5] = [
    "accepted",
    "duplicate",
    "capacity",
    "too_large",
    "runtime_rejected",
];
const ACTIONS: [&str; 9] = [
    "prevote",
    "precommit",
    "aggregate_prevote",
    "aggregate_precommit",
    "quorum",
    "proposal",
    "nil_vote",
    "round_change",
    "round_change_certificate",
];

/// Process-local observations; executed gas and transactions include replay attempts.
#[derive(Debug, Default)]
pub struct ExecutionMetrics {
    /// Ordinary WASM execution attempts, including dry runs and replays.
    pub blocks: StageMetrics,
    /// Runtime transaction validation attempts.
    pub validation: StageMetrics,
    /// Runtime read-only query attempts.
    pub queries: StageMetrics,
    /// Block imports including header verification and ordinary execution.
    pub block_imports: StageMetrics,
    /// Incoming block receipt verification and import.
    pub block_verification: StageMetrics,
    /// Incoming complete chunk receipt verification and import.
    pub chunk_verification: StageMetrics,
    /// Incoming recursive history receipt verification and import.
    pub history_verification: StageMetrics,
    /// Time from the first locally opened BFT session to its finalization.
    pub finalization: StageMetrics,
    /// Gas returned by successful ordinary execution attempts, including replay.
    pub gas: AtomicU64,
    /// Transactions in successfully executed bodies, including replay.
    pub transactions: AtomicU64,
    /// Unique newly finalized chunks observed since startup, excluding bootstrap prefixes.
    pub finalized_chunks: AtomicU64,
    /// Transactions in newly observed finalized chunks, excluding bootstrap prefixes.
    pub finalized_transactions: AtomicU64,
    /// Actual header gas in newly observed finalized chunks.
    pub finalized_gas: AtomicU64,
    /// Finalized chunks whose retained bodies could not be counted.
    pub finalized_observation_failures: AtomicU64,
    /// Highest finalized chunk accounted by this process.
    pub(crate) observed_finalized: Mutex<Option<u64>>,
    validity_codes: [AtomicU64; VALIDITY_CODES.len()],
    admissions: [AtomicU64; ADMISSIONS.len()],
    actions: [AtomicU64; ACTIONS.len()],
    timeout_actions: AtomicU64,
    opened: Mutex<BTreeMap<u64, Instant>>,
}
impl ExecutionMetrics {
    /// Record admission result using a fixed error classification.
    pub fn admission(&self, result: &Result<Hash, neutrino_mempool::InsertError>) {
        let index = match result {
            Ok(_) => 0,
            Err(neutrino_mempool::InsertError::Duplicate) => 1,
            Err(neutrino_mempool::InsertError::CapacityExceeded) => 2,
            Err(neutrino_mempool::InsertError::TooLarge) => 3,
            Err(neutrino_mempool::InsertError::RejectedByValidator) => 4,
        };
        self.admissions[index].fetch_add(1, Ordering::Relaxed);
    }
    /// Count a generated BFT action. Re-publication is intentionally counted.
    pub fn action(&self, action: &BftAction) {
        let index = match action {
            BftAction::BroadcastPrevote(_) => 0,
            BftAction::BroadcastPrecommit(_) => 1,
            BftAction::PublishAggregatePrevote { .. } => 2,
            BftAction::PublishAggregatePrecommit { .. } => 3,
            BftAction::QuorumReached(_) => 4,
            BftAction::BroadcastProposal(_) => 5,
            BftAction::BroadcastNilVote(_) => 6,
            BftAction::BroadcastRoundChange(_) => 7,
            BftAction::BroadcastRoundChangeCertificate(_) => 8,
        };
        self.actions[index].fetch_add(1, Ordering::Relaxed);
    }
    /// Count actions generated by a phase-deadline tick, including retransmission.
    pub fn timeout_actions(&self, count: usize) {
        self.timeout_actions
            .fetch_add(u64::try_from(count).unwrap_or(u64::MAX), Ordering::Relaxed);
    }
    /// Track a first local session opening with a fixed 64-entry bound.
    pub fn opened(&self, chunk: u64) {
        let mut entries = self.opened.lock().expect("BFT metrics timings");
        if entries.len() >= 64 && !entries.contains_key(&chunk) {
            entries.pop_first();
        }
        entries.entry(chunk).or_insert_with(Instant::now);
    }
    /// Record finality only after successful durable engine admission.
    pub fn finalized(&self, chunk: u64) {
        let mut entries = self.opened.lock().expect("BFT metrics timings");
        if let Some(at) = entries.remove(&chunk) {
            self.finalization.observe(at.elapsed(), true);
        }
        entries.retain(|id, _| *id > chunk);
    }
    /// Render fixed-name, fixed-label observations.
    pub fn render(&self, out: &mut String) {
        self.render_stages(out);
        for (name, help, value) in [
            (
                "neutrino_execution_gas_total",
                "Gas from successful execution attempts including replay",
                self.gas.load(Ordering::Relaxed),
            ),
            (
                "neutrino_execution_transactions_total",
                "Transactions in successful execution attempts including replay",
                self.transactions.load(Ordering::Relaxed),
            ),
            (
                "neutrino_bft_deadline_actions_total",
                "Actions produced by deadline ticks including retransmission",
                self.timeout_actions.load(Ordering::Relaxed),
            ),
        ] {
            counter(out, name, help, value);
        }
        for (name, value) in [
            (
                "neutrino_finalized_observed_chunks_total",
                &self.finalized_chunks,
            ),
            (
                "neutrino_finalized_observed_transactions_total",
                &self.finalized_transactions,
            ),
            ("neutrino_finalized_observed_gas_total", &self.finalized_gas),
            (
                "neutrino_finalized_observation_failures_total",
                &self.finalized_observation_failures,
            ),
        ] {
            counter(
                out,
                name,
                "Newly observed finalized execution since startup excluding bootstrap prefixes.",
                value.load(Ordering::Relaxed),
            );
        }
        self.render_outcomes(out);
    }
    fn render_outcomes(&self, out: &mut String) {
        family(
            out,
            "neutrino_transaction_validity_total",
            "Runtime validation verdicts including traps.",
            "counter",
        );
        for (code, count) in VALIDITY_CODES.iter().zip(&self.validity_codes) {
            let _ = writeln!(
                out,
                "neutrino_transaction_validity_total{{code=\"{code}\"}} {}",
                count.load(Ordering::Relaxed)
            );
        }
        family(
            out,
            "neutrino_transaction_admissions_total",
            "Mempool admission attempts.",
            "counter",
        );
        for (outcome, count) in ADMISSIONS.iter().zip(&self.admissions) {
            let _ = writeln!(
                out,
                "neutrino_transaction_admissions_total{{outcome=\"{outcome}\"}} {}",
                count.load(Ordering::Relaxed)
            );
        }
        family(
            out,
            "neutrino_bft_actions_total",
            "Generated BFT actions including retransmission.",
            "counter",
        );
        for (action, count) in ACTIONS.iter().zip(&self.actions) {
            let _ = writeln!(
                out,
                "neutrino_bft_actions_total{{action=\"{action}\"}} {}",
                count.load(Ordering::Relaxed)
            );
        }
    }
    fn render_stages(&self, out: &mut String) {
        for (stage, name, help) in [
            (
                &self.blocks,
                "neutrino_execution",
                "Ordinary execution including replay",
            ),
            (
                &self.validation,
                "neutrino_transaction_validation",
                "Runtime transaction validation",
            ),
            (
                &self.queries,
                "neutrino_runtime_query",
                "Read-only runtime query",
            ),
            (
                &self.block_imports,
                "neutrino_block_import",
                "Block or batch validation and import",
            ),
            (
                &self.block_verification,
                "neutrino_block_receipt_import",
                "Block receipt batch verification and import",
            ),
            (
                &self.chunk_verification,
                "neutrino_chunk_receipt_import",
                "Chunk receipt verification and import",
            ),
            (
                &self.history_verification,
                "neutrino_history_receipt_import",
                "History receipt verification and import",
            ),
            (
                &self.finalization,
                "neutrino_bft_finalization",
                "Finalization since first local session opening",
            ),
        ] {
            stage.render(out, name, help);
        }
    }
}

pub(crate) struct MeteredExecutor<X> {
    inner: X,
    metrics: Arc<NodeMetrics>,
}
impl<X> MeteredExecutor<X> {
    pub(crate) const fn new(inner: X, metrics: Arc<NodeMetrics>) -> Self {
        Self { inner, metrics }
    }
}
impl<X: ErasedBlockExecutor> ErasedBlockExecutor for MeteredExecutor<X> {
    fn execute_block(
        &self,
        ctx: &BlockExecutionContext,
        body: &Body,
        state: &mut Trie<Poseidon2Hasher>,
    ) -> Result<ExecutionOutcome, String> {
        let timer = self.metrics.execution.blocks.timer();
        let result = self.inner.execute_block(ctx, body, state);
        if let Ok(output) = &result {
            self.metrics
                .execution
                .gas
                .fetch_add(output.gas_used, Ordering::Relaxed);
            self.metrics.execution.transactions.fetch_add(
                u64::try_from(body.transactions.len()).unwrap_or(u64::MAX),
                Ordering::Relaxed,
            );
        }
        timer.finish(result.is_ok());
        result
    }
    fn query(
        &self,
        request: &QueryRequest,
        runtime_code_hash: Hash,
        state: &Trie<Poseidon2Hasher>,
    ) -> Result<QueryResponse, String> {
        let timer = self.metrics.execution.queries.timer();
        let result = self.inner.query(request, runtime_code_hash, state);
        timer.finish(result.as_ref().is_ok_and(QueryResponse::is_ok));
        result
    }
    fn validate_tx(
        &self,
        bytes: &[u8],
        chain_id: u64,
        gas_limit: u64,
        runtime_code_hash: Hash,
        state: &Trie<Poseidon2Hasher>,
    ) -> Result<TxValidity, String> {
        let timer = self.metrics.execution.validation.timer();
        let result = self
            .inner
            .validate_tx(bytes, chain_id, gas_limit, runtime_code_hash, state);
        let code = result.as_ref().map_or(RUNTIME_TRAP, |validity| {
            usize::try_from(validity.code.as_u32()).expect("bounded validity code")
        });
        self.metrics.execution.validity_codes[code].fetch_add(1, Ordering::Relaxed);
        timer.finish(result.as_ref().is_ok_and(|validity| validity.is_valid()));
        result
    }
    fn install_runtime(&self, wasm: &[u8]) -> Result<Hash, String> {
        self.inner.install_runtime(wasm)
    }
    fn alias_default_runtime(&self, hash: Hash) -> Result<(), String> {
        self.inner.alias_default_runtime(hash)
    }
    fn installed_runtimes(&self) -> Vec<Hash> {
        self.inner.installed_runtimes()
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn repeated_finality_notifications_do_not_duplicate_latency() {
        let metrics = ExecutionMetrics::default();
        metrics.opened(4);
        metrics.opened(4);
        metrics.finalized(4);
        metrics.finalized(4);
        let mut out = String::new();
        metrics.render(&mut out);
        assert!(out.contains("neutrino_bft_finalization_seconds_count 1"));
    }
    #[test]
    fn runtime_traps_are_observed_and_still_propagate() {
        let metrics = Arc::new(NodeMetrics::default());
        let executor = MeteredExecutor::new(
            neutrino_proof_system::UnsupportedExecutor,
            Arc::clone(&metrics),
        );
        let result = executor.validate_tx(&[], 1, 100, [0; 32], &Trie::<Poseidon2Hasher>::new());
        assert!(result.is_err());
        let mut out = String::new();
        metrics.execution.render(&mut out);
        assert!(out.contains("neutrino_transaction_validation_total{outcome=\"failed\"} 1"));
    }
}
